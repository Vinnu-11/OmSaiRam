import 'package:flutter_riverpod/flutter_riverpod.dart';
import '../../../core/providers/language_provider.dart';

/// Plain wording for the group screens. Falls back to English for missing
/// languages or keys. `{name}` placeholders are filled from [args].
String groupText(String code, String key, [Map<String, Object> args = const {}]) {
  var text = _text[code]?[key] ?? _text['en']![key] ?? key;
  args.forEach((name, value) => text = text.replaceAll('{$name}', '$value'));
  return text;
}

extension GroupTextRef on WidgetRef {
  /// For build methods: rebuilds when the app language changes.
  String gt(String key, [Map<String, Object> args = const {}]) =>
      groupText(watch(languageProvider).appLanguage.code, key, args);
  /// For callbacks and dialogs outside build.
  String gtr(String key, [Map<String, Object> args = const {}]) =>
      groupText(read(languageProvider).appLanguage.code, key, args);
}

